def main() -> None:
    who, base, out = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3])
    table = ACTIONS[who]
    names = sys.argv[4:] or list(table)
    todo = [n for n in names if not (out / f"{n}.mp4").exists()]
    clip = Path(__file__).with_name("clip.py")
    style = STYLES.get(who)

    def one(n: str) -> str:
        args = [sys.executable, str(clip), str(base), str(out / f"{n}.mp4"), table[n], "720P"] + ([style] if style else [])
        r = subprocess.run(args, capture_output=True, text=True)
        return f"{who}/{n}: {'ok' if r.returncode == 0 else (r.stderr.strip().splitlines() or ['失败'])[-1]}"

    with ThreadPoolExecutor(max_workers=3) as pool:  # 百炼视频并发有限，三个一组
        for line in pool.map(one, todo):
            print(line, flush=True)


if __name__ == "__main__":
    main()
