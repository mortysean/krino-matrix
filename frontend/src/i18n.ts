export type Locale = 'zh' | 'en'
const dicts: Record<Locale, Record<Key, string>> = { zh, en }

function stored(): Locale {
  try {
    const v = localStorage.getItem('krino.locale')
    if (v === 'zh' || v === 'en') return v
  } catch { /* storage unavailable */ }
  return 'zh'
}

let locale: Locale = stored()

export function getLocale(): Locale { return locale }

export function setLocale(next: Locale) {
  locale = next
  try { localStorage.setItem('krino.locale', next) } catch { /* storage unavailable */ }
  document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en'
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = dicts[locale][key] ?? zh[key]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}

export function errorText(code: string): string {
  const key = `err.${code}` as Key
  return key in zh ? t(key) : t('err.generic')
}
